/**
 * MULTI_AGENT_PLAN.md Generator
 *
 * Creates human-readable markdown files showing the agent workflow plan
 * and status for each project. This provides observability into the
 * autonomous agent system.
 *
 * Inspired by the "Autonomous Developer Swarm" blueprint.
 */

const { uploadTextFile, downloadTextFile } = require('./minio-client');

/**
 * Task status enum
 */
const TaskStatus = {
    PENDING: 'pending',
    IN_PROGRESS: 'in_progress',
    COMPLETED: 'completed',
    FAILED: 'failed',
};

/**
 * Create initial MULTI_AGENT_PLAN.md for vendor ack workflow
 *
 * @param {Object} data - Project data
 * @param {string} data.projectId - Project UUID
 * @param {string} data.projectName - Project name
 * @param {string} data.vendorName - Vendor name
 * @param {string} data.vendorOrderId - Vendor order UUID
 * @param {Object} data.jobs - Job IDs
 * @returns {Promise<string>} - MinIO path to plan file
 */
async function createVendorAckPlan(data) {
    const { projectId, projectName, vendorName, vendorOrderId, jobs } = data;

    const plan = `# MULTI_AGENT_PLAN.md

**Project:** ${projectName}
**Project ID:** ${projectId}
**Vendor:** ${vendorName}
**Vendor Order ID:** ${vendorOrderId}
**Workflow:** Vendor Acknowledgment Processing
**Created:** ${new Date().toISOString()}

---

## 🎯 Objective

Automatically process vendor acknowledgment PDF, compare with original order, detect discrepancies, and notify vendor if mismatches are found.

---

## 📋 Task Breakdown

### Task 1: OCR Vendor Acknowledgment
**Agent:** AckParserAgent
**Status:** ${TaskStatus.PENDING}
**Job ID:** ${jobs.ocrJobId}
**Description:** Parse vendor ack PDF using OpenAI Vision, extract line items, normalize door specifications

**Dependencies:** None

**Expected Output:**
- Parsed line items stored in \`ack_line_items\` table
- OCR confidence scores
- Normalized door specs (width, height, swing, price)

---

### Task 2: Compare Order vs Acknowledgment
**Agent:** CompareAgent
**Status:** ${TaskStatus.PENDING}
**Job ID:** ${jobs.compareJobId}
**Description:** Compare original vendor order line items with acknowledgment line items, apply tolerances, identify mismatches

**Dependencies:** Task 1 (OCR Ack)

**Tolerances:**
- Price: ±2.0%
- Size: ±0.25 inches

**Expected Output:**
- Comparison results in \`comparisons\` table
- Mismatch details in \`mismatch_details\` table
- Flag if discrepancies found

---

### Task 3: Generate Mismatch PDF
**Agent:** PDFGeneratorAgent
**Status:** ${TaskStatus.PENDING}
**Job ID:** (conditional - enqueued if mismatches found)
**Description:** Generate professional PDF report showing line-by-line comparison with highlighted discrepancies

**Dependencies:** Task 2 (Compare)

**Conditional:** Only runs if Task 2 detects discrepancies

**Expected Output:**
- Mismatch PDF uploaded to MinIO
- Path stored in \`comparisons.mismatch_pdf_path\`

---

### Task 4: Email Vendor
**Agent:** EmailAgent
**Status:** ${TaskStatus.PENDING}
**Job ID:** (conditional - enqueued after PDF generation)
**Description:** Send email to vendor with mismatch PDF attachment, CC internal team

**Dependencies:** Task 3 (Generate PDF)

**Conditional:** Only runs if Task 3 completes successfully

**Expected Output:**
- Email sent via SMTP
- Vendor notified of discrepancies
- Internal team CC'd

---

## 📊 Progress Summary

| Task | Agent | Status | Started | Completed | Duration |
|------|-------|--------|---------|-----------|----------|
| 1. OCR Ack | AckParserAgent | ${TaskStatus.PENDING} | - | - | - |
| 2. Compare | CompareAgent | ${TaskStatus.PENDING} | - | - | - |
| 3. Generate PDF | PDFGeneratorAgent | ${TaskStatus.PENDING} | - | - | - |
| 4. Email Vendor | EmailAgent | ${TaskStatus.PENDING} | - | - | - |

---

## 🔍 Real-Time Status

**Last Updated:** ${new Date().toISOString()}

_This plan is updated in real-time as agents complete tasks._

---

## 📝 Notes

- All times in UTC
- Job IDs link to BullMQ job tracking
- Conditional tasks only appear in queue if triggered

---

## 🏗️ Architecture

\`\`\`
Orchestrator API
    ↓
Redis Queue (BullMQ)
    ↓
┌─────────────────────┐
│  AckParserAgent     │ → Parse PDF (OpenAI Vision)
│  (Worker 1)         │ → Normalize specs
└──────────┬──────────┘
           ↓
┌─────────────────────┐
│  CompareAgent       │ → Fetch original order
│  (Worker 2)         │ → Compare line-by-line
└──────────┬──────────┘ → Apply tolerances
           ↓
┌─────────────────────┐
│  PDFGeneratorAgent  │ → Generate mismatch report
│  (Worker 3)         │ → Upload to MinIO
└──────────┬──────────┘
           ↓
┌─────────────────────┐
│  EmailAgent         │ → Send to vendor
│  (Worker 4)         │ → CC internal team
└─────────────────────┘
\`\`\`

---

_Auto-generated by Door Automation System_
`;

    // Upload to MinIO
    const planPath = await uploadTextFile(plan, projectId, 'MULTI_AGENT_PLAN.md');

    console.log(`MULTI_AGENT_PLAN.md created: ${planPath}`);

    return planPath;
}

/**
 * Update task status in MULTI_AGENT_PLAN.md
 *
 * @param {string} projectId - Project UUID
 * @param {number} taskNumber - Task number (1-4)
 * @param {string} status - New status
 * @param {Object} metadata - Optional metadata (startedAt, completedAt, error)
 */
async function updateTaskStatus(projectId, taskNumber, status, metadata = {}) {
    try {
        const planPath = `${projectId}/MULTI_AGENT_PLAN.md`;

        // Download current plan
        let plan = await downloadTextFile(planPath);

        // Update task status in the task breakdown section
        const taskHeader = `### Task ${taskNumber}:`;
        const statusLine = '**Status:**';

        const taskIndex = plan.indexOf(taskHeader);

        if (taskIndex === -1) {
            console.warn(`Task ${taskNumber} not found in plan`);
            return;
        }

        const statusIndex = plan.indexOf(statusLine, taskIndex);

        if (statusIndex === -1) {
            console.warn(`Status line not found for task ${taskNumber}`);
            return;
        }

        const statusLineEnd = plan.indexOf('\n', statusIndex);
        const currentStatusLine = plan.substring(statusIndex, statusLineEnd);

        // Create new status line with emoji
        const statusEmoji = {
            [TaskStatus.PENDING]: '⏳',
            [TaskStatus.IN_PROGRESS]: '🔄',
            [TaskStatus.COMPLETED]: '✅',
            [TaskStatus.FAILED]: '❌',
        };

        const emoji = statusEmoji[status] || '❓';
        const newStatusLine = `**Status:** ${emoji} ${status}`;

        plan = plan.replace(currentStatusLine, newStatusLine);

        // Update progress summary table
        const tableRow = `| ${taskNumber}.`;
        const tableIndex = plan.indexOf(tableRow);

        if (tableIndex !== -1) {
            const tableRowEnd = plan.indexOf('\n', tableIndex);
            const currentTableRow = plan.substring(tableIndex, tableRowEnd);

            // Parse current row
            const parts = currentTableRow.split('|').map((s) => s.trim());

            // Update status column
            parts[3] = `${emoji} ${status}`;

            // Update timestamps if provided
            if (metadata.startedAt) {
                parts[4] = new Date(metadata.startedAt).toLocaleTimeString('en-US', { hour12: false });
            }

            if (metadata.completedAt) {
                parts[5] = new Date(metadata.completedAt).toLocaleTimeString('en-US', { hour12: false });

                // Calculate duration
                if (metadata.startedAt) {
                    const duration = new Date(metadata.completedAt) - new Date(metadata.startedAt);
                    const seconds = Math.floor(duration / 1000);
                    parts[6] = `${seconds}s`;
                }
            }

            const newTableRow = `| ${parts.slice(1).join(' | ')} |`;

            plan = plan.replace(currentTableRow, newTableRow);
        }

        // Update "Last Updated" timestamp
        const lastUpdatedPattern = /\*\*Last Updated:\*\* .+/;
        plan = plan.replace(lastUpdatedPattern, `**Last Updated:** ${new Date().toISOString()}`);

        // Add error note if failed
        if (status === TaskStatus.FAILED && metadata.error) {
            const notesSection = '## 📝 Notes';
            const notesSectionIndex = plan.indexOf(notesSection);

            if (notesSectionIndex !== -1) {
                const insertIndex = plan.indexOf('\n', notesSectionIndex) + 1;
                const errorNote = `\n**⚠️ Task ${taskNumber} Failed:** ${metadata.error}\n`;

                plan = plan.substring(0, insertIndex) + errorNote + plan.substring(insertIndex);
            }
        }

        // Upload updated plan
        await uploadTextFile(plan, projectId, 'MULTI_AGENT_PLAN.md');

        console.log(`Task ${taskNumber} status updated to: ${status}`);
    } catch (error) {
        console.error('Error updating task status:', error);
        // Don't throw - plan updates are non-critical
    }
}

/**
 * Add conditional job to plan (PDF generation, email)
 *
 * @param {string} projectId - Project UUID
 * @param {number} taskNumber - Task number
 * @param {string} jobId - BullMQ job ID
 */
async function addConditionalJob(projectId, taskNumber, jobId) {
    try {
        const planPath = `${projectId}/MULTI_AGENT_PLAN.md`;

        // Download current plan
        let plan = await downloadTextFile(planPath);

        // Update job ID for conditional task
        const taskHeader = `### Task ${taskNumber}:`;
        const jobIdLine = '**Job ID:**';

        const taskIndex = plan.indexOf(taskHeader);

        if (taskIndex === -1) {
            return;
        }

        const jobIdIndex = plan.indexOf(jobIdLine, taskIndex);

        if (jobIdIndex === -1) {
            return;
        }

        const jobIdLineEnd = plan.indexOf('\n', jobIdIndex);
        const currentJobIdLine = plan.substring(jobIdIndex, jobIdLineEnd);

        const newJobIdLine = `**Job ID:** ${jobId}`;

        plan = plan.replace(currentJobIdLine, newJobIdLine);

        // Upload updated plan
        await uploadTextFile(plan, projectId, 'MULTI_AGENT_PLAN.md');

        console.log(`Conditional job ${jobId} added to task ${taskNumber}`);
    } catch (error) {
        console.error('Error adding conditional job:', error);
    }
}

/**
 * Get plan content for display
 *
 * @param {string} projectId - Project UUID
 * @returns {Promise<string>} - Plan content
 */
async function getPlan(projectId) {
    try {
        const planPath = `${projectId}/MULTI_AGENT_PLAN.md`;
        return await downloadTextFile(planPath);
    } catch (error) {
        console.error('Error getting plan:', error);
        throw error;
    }
}

module.exports = {
    TaskStatus,
    createVendorAckPlan,
    updateTaskStatus,
    addConditionalJob,
    getPlan,
};
